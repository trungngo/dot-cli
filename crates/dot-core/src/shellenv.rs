//! What `dot env --shell <shell>` prints: a sourceable file that gives an interactive shell the
//! values `dot` works with — every non-sensitive variable (as shell steps receive them, see
//! [`crate::Vars::exported`]) plus what `path` / `env` directives set up, as the last real run
//! recorded them ([`crate::runenv::EnvRecord`]).
//!
//! The output is idempotent: sourcing it twice does not add a directory to `PATH` twice.

use std::collections::BTreeMap;
use std::fmt;

use crate::runenv::{PathPosition, RunEnv};

/// A shell `dot env` can write for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shell {
    Zsh,
    Bash,
    Fish,
    Pwsh,
}

impl Shell {
    pub const ALL: [Shell; 4] = [Shell::Zsh, Shell::Bash, Shell::Fish, Shell::Pwsh];

    pub fn as_str(self) -> &'static str {
        match self {
            Shell::Zsh => "zsh",
            Shell::Bash => "bash",
            Shell::Fish => "fish",
            Shell::Pwsh => "pwsh",
        }
    }

    pub fn parse(s: &str) -> Option<Shell> {
        Shell::ALL.into_iter().find(|sh| sh.as_str() == s)
    }
}

impl fmt::Display for Shell {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Whether `n` can be a shell variable name.
fn is_env_name(n: &str) -> bool {
    !n.is_empty()
        && !n.starts_with(|c: char| c.is_ascii_digit())
        && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// The sourceable text for `shell`: `vars` (sorted by name; invalid names and `PATH` left out)
/// then the `path` entries of `env` (what `path:` steps recorded): prepended directories in
/// front of `PATH` (the first listed ends up first), appended ones after it, each only when it
/// is not already there.
pub fn render(shell: Shell, vars: &BTreeMap<String, String>, env: &RunEnv) -> String {
    let mut out = format!(
        "# Generated by `dot env --shell {shell}`; do not edit. Regenerate after `dot apply`.\n"
    );
    for (name, value) in vars {
        if !is_env_name(name) || name == "PATH" {
            continue;
        }
        out.push_str(&match shell {
            Shell::Zsh | Shell::Bash => format!("export {name}={}\n", sh_quote(value)),
            Shell::Fish => format!("set -gx {name} {}\n", fish_quote(value)),
            Shell::Pwsh => format!("$env:{name} = {}\n", pwsh_quote(value)),
        });
    }
    // Prepends are emitted last-first so that, applied in order, the first listed ends up in
    // front.
    let prepends = env
        .path
        .iter()
        .filter(|e| e.position == PathPosition::Prepend)
        .rev();
    let appends = env
        .path
        .iter()
        .filter(|e| e.position == PathPosition::Append);
    for e in prepends.chain(appends) {
        let dir = e.dir.to_string_lossy();
        let append = e.position == PathPosition::Append;
        out.push_str(&match shell {
            Shell::Zsh | Shell::Bash => {
                let q = sh_quote(&dir);
                let set = if append {
                    format!("\"${{PATH:+$PATH:}}\"{q}")
                } else {
                    format!("{q}\"${{PATH:+:$PATH}}\"")
                };
                format!("case \":$PATH:\" in *:{q}:*) ;; *) PATH={set} ;; esac\n")
            }
            Shell::Fish => {
                let q = fish_quote(&dir);
                let set = if append {
                    format!("$PATH {q}")
                } else {
                    format!("{q} $PATH")
                };
                format!("contains -- {q} $PATH; or set -gx PATH {set}\n")
            }
            Shell::Pwsh => {
                let q = pwsh_quote(&dir);
                let sep = "[IO.Path]::PathSeparator";
                let set = if append {
                    format!("$env:PATH + {sep} + {q}")
                } else {
                    format!("{q} + {sep} + $env:PATH")
                };
                format!(
                    "if (-not (($env:PATH -split {sep}) -contains {q})) {{ $env:PATH = {set} }}\n"
                )
            }
        });
    }
    if !env.path.is_empty() && matches!(shell, Shell::Zsh | Shell::Bash) {
        out.push_str("export PATH\n");
    }
    out
}

/// POSIX single quotes: `'` becomes `'\''`.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// fish single quotes: only `\` and `'` are escaped.
fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// PowerShell single quotes: `'` is doubled.
fn pwsh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;
    use crate::runenv::PathEntry;

    fn vars(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    fn path(dirs: &[(&str, PathPosition)]) -> RunEnv {
        let mut env = RunEnv::default();
        for (d, position) in dirs.iter().rev() {
            env.add_path(PathEntry {
                dir: PathBuf::from(d),
                position: *position,
                bundle: "b".into(),
            });
        }
        env
    }

    #[test]
    fn renders_each_shell_with_quoting() {
        let v = vars(&[
            ("EDITOR", "nvim"),
            ("QUOTED", "it's \\ $HOME"),
            ("PATH", "/nope"),
            ("bad-name", "x"),
        ]);
        let env = path(&[
            ("/a b", PathPosition::Prepend),
            ("/c", PathPosition::Prepend),
            ("/z", PathPosition::Append),
        ]);
        let zsh = render(Shell::Zsh, &v, &env);
        assert!(zsh.contains("export EDITOR='nvim'\n"), "{zsh}");
        assert!(zsh.contains("export QUOTED='it'\\''s \\ $HOME'\n"), "{zsh}");
        assert!(!zsh.contains("/nope") && !zsh.contains("bad-name"), "{zsh}");
        let c = zsh.find("PATH='/c'").unwrap();
        let a = zsh.find("PATH='/a b'").unwrap();
        assert!(c < a, "the first directory is prepended last: {zsh}");
        assert!(zsh.contains("PATH=\"${PATH:+$PATH:}\"'/z'"), "{zsh}");
        assert!(zsh.ends_with("export PATH\n"));
        assert_eq!(
            render(Shell::Bash, &v, &env),
            zsh.replace("--shell zsh", "--shell bash")
        );

        let fish = render(Shell::Fish, &v, &env);
        assert!(
            fish.contains("set -gx QUOTED 'it\\'s \\\\ $HOME'\n"),
            "{fish}"
        );
        assert!(fish.contains("contains -- '/a b' $PATH; or set -gx PATH '/a b' $PATH\n"));
        assert!(fish.contains("or set -gx PATH $PATH '/z'\n"), "{fish}");

        let pwsh = render(Shell::Pwsh, &v, &env);
        assert!(pwsh.contains("$env:QUOTED = 'it''s \\ $HOME'\n"), "{pwsh}");
        assert!(pwsh.contains("-contains '/c'"), "{pwsh}");
        assert!(
            pwsh.contains("'/a b' + [IO.Path]::PathSeparator + $env:PATH"),
            "{pwsh}"
        );

        assert_eq!(Shell::parse("fish"), Some(Shell::Fish));
        assert_eq!(Shell::parse("csh"), None);
    }

    #[cfg(unix)]
    #[test]
    fn sourcing_twice_adds_a_directory_once() {
        let v = vars(&[("GREETING", "it's here")]);
        let env = path(&[
            ("/opt/dot test/bin", PathPosition::Prepend),
            ("/opt/first", PathPosition::Prepend),
            ("/opt/late", PathPosition::Append),
        ]);
        let text = render(Shell::Bash, &v, &env);
        let tmp = tempfile::tempdir().unwrap();
        let f = tmp.path().join("env.sh");
        std::fs::write(&f, text).unwrap();
        let out = std::process::Command::new("sh")
            .arg("-c")
            .arg(format!(
                ". '{0}'; . '{0}'; printf '%s\\n%s\\n' \"$GREETING\" \"$PATH\"",
                f.display()
            ))
            .env("PATH", "/usr/bin:/bin")
            .output()
            .unwrap();
        let out = String::from_utf8(out.stdout).unwrap();
        assert_eq!(
            out,
            "it's here\n/opt/dot test/bin:/opt/first:/usr/bin:/bin:/opt/late\n"
        );
    }
}
